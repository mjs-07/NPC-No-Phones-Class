import "@supabase/functions-js/edge-runtime.d.ts";
import { withSupabase } from "@supabase/server";

export default {
  fetch: withSupabase(
    { auth: "user" },
    async (req, ctx) => {
      // Only POST requests are allowed
      if (req.method !== "POST") {
        return Response.json(
          { error: "Method not allowed" },
          { status: 405 }
        );
      }

      // Get the authenticated user's ID from the verified JWT
      const userId = ctx.userClaims?.id;

      if (!userId) {
        return Response.json(
          { error: "Unauthorized" },
          { status: 401 }
        );
      }

      // Look up the faculty profile using the server-side admin client.
      // The client never gets to choose which faculty account owns the session.
      const { data: faculty, error: facultyError } =
        await ctx.supabaseAdmin
          .from("faculties")
          .select("id")
          .eq("auth_user_id", userId)
          .maybeSingle();

      if (facultyError) {
        console.error("Faculty lookup failed:", facultyError);

        return Response.json(
          { error: "Unable to verify faculty account" },
          { status: 500 }
        );
      }

      // Authenticated user exists, but is not a faculty member.
      if (!faculty) {
        return Response.json(
          { error: "Faculty access required" },
          { status: 403 }
        );
      }

      // Check whether this faculty already has an active session.
      const { data: existingSession, error: existingError } =
        await ctx.supabaseAdmin
          .from("sessions")
          .select("id, status, started_at, ended_at")
          .eq("faculty_id", faculty.id)
          .eq("status", "ACTIVE")
          .maybeSingle();

      if (existingError) {
        console.error("Active session lookup failed:", existingError);

        return Response.json(
          { error: "Unable to check active session" },
          { status: 500 }
        );
      }

      if (existingSession) {
        return Response.json(
          {
            error: "An active classroom session already exists.",
            session: existingSession,
          },
          { status: 409 }
        );
      }

      // Create the session.
      // started_at and status are intentionally generated by PostgreSQL defaults.
      const { data: session, error: insertError } =
        await ctx.supabaseAdmin
          .from("sessions")
          .insert({
            faculty_id: faculty.id,
          })
          .select("id, faculty_id, status, started_at, ended_at, created_at")
          .single();

      if (insertError) {
        console.error("Session creation failed:", insertError);

        // PostgreSQL unique-constraint violation.
        // This protects us against two simultaneous create-session requests.
        if (insertError.code === "23505") {
          return Response.json(
            { error: "An active classroom session already exists." },
            { status: 409 }
          );
        }

        return Response.json(
          { error: "Unable to create classroom session" },
          { status: 500 }
        );
      }

      return Response.json(
        {
          message: "Classroom session started successfully.",
          session,
        },
        { status: 201 }
      );
    }
  ),
};